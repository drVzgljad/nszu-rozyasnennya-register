  const cap = s => String(s || "").charAt(0).toUpperCase() + String(s || "").slice(1);

  function mix() {
    let x = 0x9e3779b9;
    for (let i = 0; i < arguments.length; i++) {
      x ^= (arguments[i] | 0) + 0x9e3779b9 + (x << 6) + (x >>> 2);
      x |= 0;
    }
    return x >>> 0;
  }

  function rng(seed) {
    let s = (seed >>> 0) || 1;
    return function () {
      s ^= s << 13; s >>>= 0;
      s ^= s >>> 17;
      s ^= s << 5; s >>>= 0;
      return s / 4294967296;
    };
  }

  // Вибір «колодою»: на кожен цикл довжиною в пул будується власна перестановка,
  // тож у межах циклу жоден текст не повторюється — пул проходиться повністю.
  // Раніше індекс брався просто за модулем, і збіги випадали через кілька днів.
  function fromDeck(pool, stream, signIndex, day) {
    const size = pool.length;
    const cycle = Math.floor(day / size);
    const next = rng(mix(stream, signIndex, cycle, YEAR));
    const order = pool.map((_, i) => i);
    for (let i = size - 1; i > 0; i--) {
      const j = Math.floor(next() * (i + 1));
      const tmp = order[i]; order[i] = order[j]; order[j] = tmp;
    }
    return pool[order[((day % size) + size) % size]];
  }

  function iso(date) {
    return date.toISOString().slice(0, 10);
  }

  function parseDate(value) {
    return new Date(value + "T00:00:00Z");
  }

  function dayIndex(date) {
    return Math.round((date.getTime() - Date.UTC(YEAR, 0, 1)) / 86400000);
  }

  function safeDate(value) {
    const date = parseDate(value);
    return Number.isFinite(date.getTime()) && date.getUTCFullYear() === YEAR ? date : new Date(Date.UTC(YEAR, 0, 1));
  }

  function currentYearDate() {
    const now = new Date();
    if (now.getFullYear() === YEAR) return new Date(Date.UTC(YEAR, now.getMonth(), now.getDate()));
    return new Date(Date.UTC(YEAR, 0, 1));
  }

