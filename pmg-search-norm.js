/* Нормалізація пошуку довідників — один модуль на весь портал.
 *
 * Аудит «Довідників» 11.11.2026 (В-3, В-4, В-5) знайшов одне й те саме в
 * чотирьох розділах (НК 025, НК 026, Таблиця співставлення, Кодування
 * випадку): пошук порівнював рядки «як є», а дані й запити набрано по-різному.
 *   В-3  апострофи: у назвах і «'», і «’», а розширена українська розкладка
 *        Windows дає «ʼ» (U+02BC) — «мʼяз» не знаходив нічого;
 *   В-4  латинські двійники всередині кириличних слів у назвах («Спiнальна» з
 *        латинською i, «cальпінгопластика» з латинською c);
 *   В-5  кирилична літера в коді («С18.9», «М51») і код ACHI без дефіса
 *        («3680901»).
 * Кожен розділ мав власну часткову латку, і всі різні. Тут — одна.
 *
 * Підключати звичайним <script> ДО скрипта розділу:
 *   <script src="../pmg-search-norm.js?v=1" defer></script>
 *
 * PMG_SEARCH.text(s) — для назв і текстових запитів. Нормалізуються ОБИДВІ
 *   сторони порівняння, тож заміна латинських двійників на кирилицю безпечна і
 *   для латинських назв (Clostridium → та сама форма в запиті й у назві).
 *   Довжина рядка зберігається (кожен символ → один символ, без trim), щоб
 *   позицію збігу можна було перенести на оригінал для підсвічування.
 * PMG_SEARCH.code(s) — для кодів: верхній регістр, без пробілів, кирилиця →
 *   латиниця, сім цифр → ACHI з дефісом (3680901 → 36809-01).
 * PMG_SEARCH.dash(s) — нерозривний та інші дефіси-двійники → «-» (символ на символ).
 *   Робиться і в text(), і в code(); розділи, що шукають код регулярним виразом
 *   у сирому вводі, пропускають ввід через dash() до розбору.
 */
(function (g) {
  'use strict';
  const APOS = /[ʼ’‘`´]/g;
  // латинські двійники кирилиці (після toLowerCase)
  const LAT2CYR = { a: 'а', c: 'с', e: 'е', i: 'і', o: 'о', p: 'р', x: 'х', y: 'у', k: 'к' };
  // кириличні двійники латиниці в кодах (як CYR2LAT у tools/kody.py)
  const CYR2LAT = { 'А': 'A', 'В': 'B', 'С': 'C', 'Е': 'E', 'Н': 'H', 'І': 'I', 'К': 'K',
                    'М': 'M', 'О': 'O', 'Р': 'P', 'Т': 'T', 'Х': 'X', 'У': 'Y' };

  // Дефіси-двійники: нерозривний «‑» (U+2011) ставлять генератори docx у кодах (30511‑09), Word
  // автозаміною дає «–», «−» буває з PDF. Скопійований із записки код інакше не впізнається (23.11.2026).
  const DASH = /[‐-―−﹘﹣－]/g;
  function dash(s) {
    return String(s == null ? '' : s).replace(DASH, '-');
  }

  function text(s) {
    return dash(s).toLowerCase()
      .replace(APOS, "'")
      .replace(/[aceiopxyk]/g, (ch) => LAT2CYR[ch]);
  }

  function code(s) {
    let t = dash(s).toUpperCase().replace(/\s+/g, '')
      .replace(/[АВСЕНІКМОРТХУ]/g, (ch) => CYR2LAT[ch]);
    if (/^\d{7}$/.test(t)) t = t.slice(0, 5) + '-' + t.slice(5);
    return t;
  }

  // ── варіанти вводу ─────────────────────────────────────────────────────
  // Бібліотека того, як людина набирає не те, що мала на увазі. Кожен варіант — інше прочитання
  // ВСЬОГО запиту; пошук пробує їх лише тоді, коли запит як є нічого не знайшов (pmg-code-search.js).
  //   layout   — забули перемкнути розкладку: «rfh,fvfptgsy» → «карбамазепін»;
  //   translit — набрано латиницею: «karbamazepin» → «карбамазепін», «kista beikera» → «кіста бейкера»;
  //   ru       — російські літери: «эпилепсия» → «епілепсія» (ы→и, э→е, ё→йо, ъ→'; «и» лишається,
  //              її замінить щабель опечаток — «карбамазепин» ~ «карбамазепін»).
  // Опечатки всередині слова тут не розбираються: їх виправляє пошук, бо для цього треба знати
  // слова довідника (див. PMG_FIND, щабель «схоже написання»).
  const EN2UA = {
    q: 'й', w: 'ц', e: 'у', r: 'к', t: 'е', y: 'н', u: 'г', i: 'ш', o: 'щ', p: 'з', '[': 'х', ']': 'ї',
    a: 'ф', s: 'і', d: 'в', f: 'а', g: 'п', h: 'р', j: 'о', k: 'л', l: 'д', ';': 'ж', "'": 'є',
    z: 'я', x: 'ч', c: 'с', v: 'м', b: 'и', n: 'т', m: 'ь', ',': 'б', '.': 'ю', '`': "'",
  };
  const TRANSLIT = [
    ['shch', 'щ'], ['sch', 'щ'], ['zh', 'ж'], ['kh', 'х'], ['ts', 'ц'], ['ch', 'ч'], ['sh', 'ш'],
    ['yu', 'ю'], ['iu', 'ю'], ['ya', 'я'], ['ia', 'я'], ['ye', 'є'], ['ie', 'є'], ['yi', 'ї'], ['ji', 'ї'],
    ['a', 'а'], ['b', 'б'], ['v', 'в'], ['w', 'в'], ['h', 'г'], ['g', 'г'], ['d', 'д'], ['e', 'е'],
    ['z', 'з'], ['y', 'и'], ['i', 'і'], ['j', 'й'], ['k', 'к'], ['c', 'к'], ['q', 'к'], ['l', 'л'],
    ['m', 'м'], ['n', 'н'], ['o', 'о'], ['p', 'п'], ['r', 'р'], ['s', 'с'], ['t', 'т'], ['u', 'у'],
    ['f', 'ф'], ['x', 'кс'],
  ];
  const RU2UA = { 'ы': 'и', 'э': 'е', 'ё': 'йо', 'ъ': "'" };

  function translit(s) {
    let out = '';
    for (let i = 0; i < s.length;) {
      const hit = TRANSLIT.find(([lat]) => s.startsWith(lat, i));
      if (hit) { out += hit[1]; i += hit[0].length; } else { out += s[i]; i += 1; }
    }
    return out;
  }

  /** Інші прочитання запиту: [{text, why}]. Порожній масив — читати нема як інакше. */
  function variants(raw) {
    const s = dash(raw).toLowerCase().trim();
    const out = [];
    if (!s) return out;
    const hasLat = /[a-z]/.test(s), hasCyr = /[а-яіїєґёыэъ]/.test(s);
    // латиниця без кирилиці: або не та розкладка, або транслітерація. Схоже на код — не чіпаємо.
    if (hasLat && !hasCyr && !/^[a-z]\d/.test(s) && !/\d{3}/.test(s)) {
      out.push({ text: s.replace(/[a-z;',.\[\]`]/g, (ch) => EN2UA[ch] || ch), why: 'не та розкладка клавіатури' });
      out.push({ text: translit(s), why: 'набрано латиницею' });
    }
    if (/[ыэёъ]/.test(s)) out.push({ text: s.replace(/[ыэёъ]/g, (ch) => RU2UA[ch]), why: 'російські літери' });
    return out.filter((v) => v.text !== s);
  }

  g.PMG_SEARCH = { text, code, dash, variants };
})(typeof window !== 'undefined' ? window : globalThis);
