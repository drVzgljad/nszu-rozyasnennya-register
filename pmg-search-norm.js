/* Нормалізація пошуку довідників — один модуль на весь портал.
 *
 * Аудит «Довідників» 11.11.2026 (В-3, В-4, В-5) знайшов одне й те саме в
 * чотирьох розділах (НК 025, НК 026, Таблиця співставлення, Кодування
 * випадку): пошук порівнював рядки «як є», а дані й запити набрано по-різному.
 *   В-3  апострофи: у назвах і «'», і «’», а розширена українська розкладка
 *        Windows дає «ʼ» (U+02BC) — «мʼяз» не знаходив нічого;
 *   В-4  латинські двійники всередині кириличних слів у назвах («Спiнальна» з
 *        латинською i, «cальпінгопластика» з латинською c);
 *   В-5  кирилична літера в коді («С18.9», «М51») і код ACHI без дефіса
 *        («3680901»).
 * Кожен розділ мав власну часткову латку, і всі різні. Тут — одна.
 *
 * Підключати звичайним <script> ДО скрипта розділу:
 *   <script src="../pmg-search-norm.js?v=1" defer></script>
 *
 * PMG_SEARCH.text(s) — для назв і текстових запитів. Нормалізуються ОБИДВІ
 *   сторони порівняння, тож заміна латинських двійників на кирилицю безпечна і
 *   для латинських назв (Clostridium → та сама форма в запиті й у назві).
 *   Довжина рядка зберігається (кожен символ → один символ, без trim), щоб
 *   позицію збігу можна було перенести на оригінал для підсвічування.
 * PMG_SEARCH.code(s) — для кодів: верхній регістр, без пробілів, кирилиця →
 *   латиниця, сім цифр → ACHI з дефісом (3680901 → 36809-01).
 */
(function (g) {
  'use strict';
  const APOS = /[ʼ’‘`´]/g;
  // латинські двійники кирилиці (після toLowerCase)
  const LAT2CYR = { a: 'а', c: 'с', e: 'е', i: 'і', o: 'о', p: 'р', x: 'х', y: 'у', k: 'к' };
  // кириличні двійники латиниці в кодах (як CYR2LAT у tools/kody.py)
  const CYR2LAT = { 'А': 'A', 'В': 'B', 'С': 'C', 'Е': 'E', 'Н': 'H', 'І': 'I', 'К': 'K',
                    'М': 'M', 'О': 'O', 'Р': 'P', 'Т': 'T', 'Х': 'X', 'У': 'Y' };

  function text(s) {
    return String(s == null ? '' : s).toLowerCase()
      .replace(APOS, "'")
      .replace(/[aceiopxyk]/g, (ch) => LAT2CYR[ch]);
  }

  function code(s) {
    let t = String(s == null ? '' : s).toUpperCase().replace(/\s+/g, '')
      .replace(/[АВСЕНІКМОРТХУ]/g, (ch) => CYR2LAT[ch]);
    if (/^\d{7}$/.test(t)) t = t.slice(0, 5) + '-' + t.slice(5);
    return t;
  }

  g.PMG_SEARCH = { text, code };
})(window);
