# -*- coding: utf-8 -*-
"""
Білдер Переліку медичного обладнання за наказом МОЗ від 22.04.2025 № 697.

Наказ зобов'язує ЗОЗ вносити це обладнання до Реєстру суб'єктів господарювання
в ЕСОЗ — назву й код типу СУВОРО за Переліком. Для порталу це найцінніше з
усього, що є про обладнання: **нормативний** місток «назва договірною мовою ↔
код НК 031», якого більше ніде не існує. Специфікації пакетів говорять тією
самою мовою, що й Перелік, а НК 031 — своєю:

    C019004    наказ 697: «Система моніторингу фізіологічних показників»
               НК 031:    «СИСТЕМИ СЕРЦЕВО-СУДИННОГО МОНІТОРИНГУ»

Тому Перелік у білдері обладнання стоїть ВИЩЕ за будь-яке обчислене
зіставлення: це не здогад із ваг, а норма.

ПАСТКИ (перевірено 04.08.2026):
  1. Таблиця тягнеться через шість сторінок, і PyMuPDF подекуди зліплює хвіст
     одного рядка з початком наступного в один рядок тексту:
     «…загального призначення Z12010902 71 Електрохірургічний апарат…».
     Через це наївний парсер зупиняється на 70 позиціях замість 84.
  2. Назва типу може займати два-три візуальні рядки, код завжди останній.
  3. Перша позиція йде одразу за шапкою «№ з/п / Назва типу / Код» і рядком
     нумерації колонок «1 2 3» — його треба відкинути, інакше «1» шапки
     з'їдається як номер першої позиції.

Джерело: 0_10_класификатори/…Наказ № 697 від 22.04.2025…pdf
Вихід: ./data/equipment/nakaz697.json
"""
import json, re, sys, time
from pathlib import Path

import fitz

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

BASE = Path(__file__).resolve().parent
OUT = BASE / "data" / "equipment" / "nakaz697.json"
SRC = next(Path(r"D:\pmg-data\0_10_класификатори").glob("*697*.pdf"), None)
NK031 = BASE / "data" / "nk031" / "nk031_index.json"

CODE = re.compile(r"^[A-ZА-Я]\d{4,}$")
# Код, що прилип до хвоста назви в тому самому рядку:
# «Електрохірургічний апарат (ЕХА) загального призначення Z12010902»
GLUED = re.compile(r"^(.*\S)[ \t]+([A-ZА-Я]\d{4,})$", re.M)


def log(msg):
    print(f"[{time.strftime('%H:%M:%S')}] {msg}", flush=True)


def parse(path):
    doc = fitz.open(path)
    text = "\n".join(doc[i].get_text() for i in range(doc.page_count))

    # Таблиця йде від шапки «№ з/п / Назва типу / Код» і рядка нумерації
    # колонок «1 2 3» до підпису директора департаменту. Ріжемо саме так, а не
    # по номерах сторінок: у наказ вносили зміни, і сторінки попливуть.
    head = re.search(r"Назва\s+типу\s*\n\s*Код\s*\n\s*1\s*\n\s*2\s*\n\s*3\s*\n", text)
    if not head:
        sys.exit("Не знайдено шапку таблиці Переліку — перевір PDF")
    tail = text.find("Директор Департаменту", head.end())
    text = text[head.end(): tail if tail > 0 else len(text)]
    text = GLUED.sub(r"\1\n\2", text)            # пастка 1

    lines = [l.strip() for l in text.split("\n") if l.strip()]
    rows, i, expect = [], 0, 1
    while i < len(lines):
        if lines[i] == str(expect) and not CODE.match(lines[i]):
            i += 1
            name = []
            while i < len(lines) and not CODE.match(lines[i]):
                name.append(lines[i])
                i += 1
            if i < len(lines) and name:
                rows.append({"n": expect, "name": " ".join(name).strip(), "code": lines[i]})
                expect += 1
                i += 1
                continue
        i += 1
    doc.close()
    return rows


def build():
    if not SRC or not SRC.exists():
        sys.exit("Не знайдено PDF наказу 697")
    rows = parse(SRC)
    log(f"Перелік: {len(rows)} типів обладнання")

    # Звірка з НК 031: код Переліку МУСИТЬ там бути. Якщо ні — або наказ
    # посилається на позицію, якої в нашій вигрузці немає, або зламався парсер.
    nk = {}
    if NK031.exists():
        nk = {r[0]: r[1] for r in json.loads(NK031.read_text(encoding="utf-8"))}
    miss = [r for r in rows if r["code"] not in nk]
    for r in rows:
        r["nk031"] = nk.get(r["code"], "")
    log(f"Звірка з НК 031: {len(rows) - len(miss)} з {len(rows)} кодів знайдено"
        + (f"; НЕ знайдено: {[r['code'] for r in miss]}" if miss else ""))

    out = {
        "generated": time.strftime("%Y-%m-%d"),
        "order": {
            "title": "Перелік медичного обладнання",
            "act": "наказ МОЗ від 22.04.2025 № 697",
            "registered": "Мін'юст 28.04.2025 за № 633/44039",
            "amended": "зі змінами за наказом МОЗ від 30.04.2025 № 754",
            "url": "https://zakon.rada.gov.ua/go/z0633-25",
            "purpose": "Обладнання з цього Переліку ЗОЗ вносить до Реєстру суб'єктів "
                       "господарювання в ЕСОЗ — назву й код типу вказують за Переліком.",
        },
        # Що саме ЗОЗ вносить у Реєстр (Зміни до Порядку, затвердженого наказом
        # МОЗ від 18.10.2021 № 2243) — питання, яке ставлять постійно.
        "attributes": [
            "назва та код типу — за Переліком",
            "місце надання медичних послуг, де знаходиться обладнання (за необхідності)",
            "виробник, дата виробництва, номер моделі, серійний номер (за наявності)",
            "інвентарний номер, номер закупівлі, строк експлуатації (за наявності)",
            "статус запису: активний / неактивний / внесено помилково",
            "статус доступності: доступний / відсутній / пошкоджений / не підлягає відновленню",
        ],
        "types": rows,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, ensure_ascii=False, separators=(",", ":")),
                   encoding="utf-8")
    log(f"  → {OUT.name}  {OUT.stat().st_size // 1024} КБ")


if __name__ == "__main__":
    build()
