const ALL = SETS.flatMap(([, , list]) => list);

export function recent() {
  try { return JSON.parse(localStorage.getItem(LS_RECENT) || '[]').slice(0, 24); } catch (_) { return []; }
}

export function remember(e) {
  try {
    const list = [e, ...recent().filter((x) => x !== e)].slice(0, 24);
    localStorage.setItem(LS_RECENT, JSON.stringify(list));
  } catch (_) { /* приватний режим */ }
}

export function search(q) {
  const s = q.trim().toLowerCase();
  if (!s) return [];
  return ALL.filter(([e, words]) => e === s || words.split(/\s+/).some((w) => w.startsWith(s))).map(([e]) => e);
}

/** 1–3 емодзі без тексту — повідомлення показуємо великим (як у старому чаті). */
export function emojiOnly(text) {
  const t = (text || '').replace(/\s+/g, '');
  if (!t || t.length > 40) return false;
  if (!/^(?:\p{Extended_Pictographic}|\p{Emoji_Modifier}|\p{Regional_Indicator}|‍|️)+$/u.test(t)) return false;
  const n = [...t.matchAll(/\p{Extended_Pictographic}|\p{Regional_Indicator}{2}/gu)].length;
  return n > 0 && n <= 3;
}

/**
 * Панель вибору. onPick(e) — що робити з вибраним. Повертає елемент панелі,
 * який викликач сам ставить на місце й показує/ховає.
 */
export function buildPicker(onPick) {
  const el = document.createElement('div');
  el.className = 'zv-emoji';
  el.setAttribute('role', 'dialog');
  el.setAttribute('aria-label', 'Смайлики');
  el.hidden = true;
  const tabs = [['Нещодавні', '🕘'], ...SETS.map(([n, i]) => [n, i])];
  el.innerHTML = `
    <input class="zv-emoji-q" type="search" placeholder="Пошук: так, дякую, лікар…" aria-label="Пошук смайлика">
    <div class="zv-emoji-tabs" role="tablist">${tabs.map(([n, i], idx) =>
      `<button type="button" role="tab" data-tab="${idx}" title="${n}" aria-label="${n}">${i}</button>`).join('')}</div>
    <div class="zv-emoji-grid" role="listbox" aria-label="Смайлики"></div>`;
  const grid = el.querySelector('.zv-emoji-grid');
  const q = el.querySelector('.zv-emoji-q');
  let tab = recent().length ? 0 : 1;

  const fill = (list, empty) => {
    grid.innerHTML = list.length
      ? list.map((e) => `<button type="button" role="option" data-e="${e}">${e}</button>`).join('')
      : `<p class="zv-emoji-empty">${empty}</p>`;
  };
  const show = () => {
    el.querySelectorAll('[data-tab]').forEach((b) => b.setAttribute('aria-selected', String(+b.dataset.tab === tab)));
    if (tab === 0) fill(recent(), 'Тут з\'являться смайлики, які ви вибирали.');
    else fill(SETS[tab - 1][2].map(([e]) => e), '');
  };
  el.addEventListener('click', (ev) => {
    const t = ev.target.closest('[data-tab]');
    if (t) { tab = +t.dataset.tab; q.value = ''; show(); return; }
    const b = ev.target.closest('[data-e]');
    if (b) { remember(b.dataset.e); onPick(b.dataset.e); }
  });
  q.addEventListener('input', () => {
    if (!q.value.trim()) return show();
    fill(search(q.value), 'Нічого не знайдено.');
  });
  el.addEventListener('keydown', (ev) => { if (ev.key === 'Escape') { el.hidden = true; ev.stopPropagation(); } });
  el.refresh = () => { tab = recent().length ? 0 : 1; q.value = ''; show(); };
  show();
  return el;
}
