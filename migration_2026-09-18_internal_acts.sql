-- ─────────────────────────────────────────────────────────────
-- 1. Реєстр внутрішніх актів: чинні, проєкти на погодженні, наші позиції
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.internal_acts (
  id          BIGSERIAL PRIMARY KEY,
  kind        TEXT NOT NULL CHECK (kind IN ('chynnyi', 'proekt', 'pozytsiia')),
  title       TEXT NOT NULL,
  requisites  TEXT,                -- «наказ НСЗУ від 15.09.2026 № 502»
  act_date    DATE,
  developer   TEXT,                -- розробник проєкту
  status      TEXT,                -- чинний · на погодженні · подано · замінено
  regulates   TEXT,                -- що регулює / про що документ
  our_role    TEXT,                -- наша роль у ньому
  notes       TEXT,
  doc_path    TEXT,                -- де лежить файл у робочій теці
  sort        INT DEFAULT 0,
  updated_at  TIMESTAMPTZ DEFAULT now()
);

COMMENT ON TABLE public.internal_acts IS
  'Реєстр внутрішніх організаційно-розпорядчих актів НСЗУ (накази, порядки, '
  'алгоритми) і наших позицій до їхніх проєктів. Дзеркало теки '
  'D:\pmg-data\28_внутрішні_акти_НСЗУ. Не публічне: під RLS.';

-- ─────────────────────────────────────────────────────────────
-- 2. Додаток 2 наказу № 502: хто який лист опрацьовує
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.internal_act_units (
  n           INT PRIMARY KEY,     -- позиція в Додатку 2 (1..26)
  unit        TEXT NOT NULL,
  official    TEXT,                -- хто робить первинний розгляд
  blocks      JSONB NOT NULL,      -- [{intro, items[], official}]
  is_ours     BOOLEAN DEFAULT false,
  updated_at  TIMESTAMPTZ DEFAULT now()
);

COMMENT ON TABLE public.internal_act_units IS
  'Додаток 2 до Алгоритму розгляду вхідної кореспонденції (наказ НСЗУ від '
  '15.09.2026 № 502): підрозділ → типи листів → посадова особа первинного '
  'розгляду. Наш департамент — позиція 18 (is_ours = true).';

-- ─────────────────────────────────────────────────────────────
-- 3. RLS: читають усі авторизовані, крім гостей; пишуть керівництво й адмін
--    (та сама межа, що в provider_private)
-- ─────────────────────────────────────────────────────────────
ALTER TABLE public.internal_acts      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.internal_act_units ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "ia_select" ON public.internal_acts;
CREATE POLICY "ia_select" ON public.internal_acts
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = auth.uid() AND p.role <> 'guest'
    )
  );

DROP POLICY IF EXISTS "ia_write" ON public.internal_acts;
CREATE POLICY "ia_write" ON public.internal_acts
  FOR ALL TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = auth.uid()
        AND (p.role IN ('admin', 'director', 'deputy_director', 'manager') OR p.is_head = true)
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = auth.uid()
        AND (p.role IN ('admin', 'director', 'deputy_director', 'manager') OR p.is_head = true)
    )
  );

DROP POLICY IF EXISTS "iau_select" ON public.internal_act_units;
CREATE POLICY "iau_select" ON public.internal_act_units
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = auth.uid() AND p.role <> 'guest'
    )
  );

DROP POLICY IF EXISTS "iau_write" ON public.internal_act_units;
CREATE POLICY "iau_write" ON public.internal_act_units
  FOR ALL TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = auth.uid()
        AND (p.role IN ('admin', 'director', 'deputy_director', 'manager') OR p.is_head = true)
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = auth.uid()
        AND (p.role IN ('admin', 'director', 'deputy_director', 'manager') OR p.is_head = true)
    )
  );

